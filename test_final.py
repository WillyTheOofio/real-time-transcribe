# 4. KEYWORD EXTRACTION
# ============================================================

def extract_keywords(text, top_k=TOP_KEYWORDS):

    print("\nExtracting keywords...")

    from nltk.corpus import stopwords

    stop_words = set(
        stopwords.words("english")
    )

    tokens = nltk.word_tokenize(
        text.lower()
    )

    words = []

    for word in tokens:

        if not word.isalpha():
            continue

        if word in stop_words:
            continue

        if len(word) < 3:
            continue

        words.append(word)

    if not words:
        return []

    frequency = Counter(words)

    candidates = [
        word
        for word, count in frequency.most_common(20)
    ]

    # --------------------------------------------------------
    # Use sentence embeddings to avoid simply returning
    # repetitive high-frequency words.
    # --------------------------------------------------------

    try:

        text_embedding = embed_model.encode(
            [text],
            normalize_embeddings=True
        )[0]

        candidate_embeddings = embed_model.encode(
            candidates,
            normalize_embeddings=True
        )

        scores = []

        for word, embedding in zip(
            candidates,
            candidate_embeddings
        ):

            similarity = float(
                np.dot(
                    text_embedding,
                    embedding
                )
            )

            frequency_score = frequency[word]

            combined_score = (
                similarity * 0.7
                + frequency_score * 0.03
            )

            scores.append(
                (word, combined_score)
            )

        scores.sort(
            key=lambda x: x[1],
            reverse=True
        )

        return [
            word
            for word, _ in scores[:top_k]
        ]

    except Exception:

        return [
            word
            for word, _ in frequency.most_common(top_k)
        ]


