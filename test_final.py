# 2. TRANSCRIBE WITH WHISPERX
# ============================================================

def transcribe_audio(audio_path):

    print("\n" + "=" * 60)
    print("TRANSCRIPTION")
    print("=" * 60)

    print("\nLoading audio...")

    audio = whisperx.load_audio(audio_path)

    print("Running WhisperX transcription...")
    print("This can take a while with large-v3.")

    result = whisper_model.transcribe(
        audio,
        batch_size=8,
        language=None
    )

    print("\nInitial transcription completed.")

    # --------------------------------------------------------
    # Alignment
    # --------------------------------------------------------

    detected_language = result.get("language", "en")

    print("Detected language:", detected_language)

    try:

        print("\nLoading alignment model...")

        model_a, metadata = whisperx.load_align_model(
            language_code=detected_language,
            device=DEVICE
        )

        result = whisperx.align(
            result["segments"],
            model_a,
            metadata,
            audio,
            DEVICE,
            return_char_alignments=False
        )

        print("Word alignment completed.")

    except Exception as e:

        print("\nWARNING: Alignment failed.")
        print("Continuing without alignment.")
        print("Reason:", e)

    return audio, result


