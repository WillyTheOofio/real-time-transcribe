# 5. PHI-3 GENERATION
# ============================================================

def generate_with_phi(
    prompt,
    max_new_tokens=MAX_NEW_TOKENS
):

    messages = [
        {
            "role": "system",
            "content": (
                "You are a professional meeting-analysis "
                "assistant. Be factual, concise, objective, "
                "and constructive. Do not invent information "
                "that is not contained in the meeting."
            )
        },
        {
            "role": "user",
            "content": prompt
        }
    ]

    formatted_prompt = tokenizer.apply_chat_template(
        messages,
        tokenize=False,
        add_generation_prompt=True
    )

    inputs = tokenizer(
        formatted_prompt,
        return_tensors="pt",
        truncation=True,
        max_length=3500
    )

    if DEVICE == "cuda":

        inputs = {
            key: value.to(DEVICE)
            for key, value in inputs.items()
        }

    with torch.no_grad():

        outputs = phi_model.generate(
            **inputs,
            max_new_tokens=max_new_tokens,
            do_sample=True,
            temperature=0.3,
            top_p=0.9,
            repetition_penalty=1.05
        )

    generated = outputs[
        0
    ][inputs["input_ids"].shape[1]:]

    response = tokenizer.decode(
        generated,
        skip_special_tokens=True
    ).strip()

    return response


# ============================================================
# 6. KEYWORD DESCRIPTIONS
# ============================================================

def generate_keyword_descriptions(
    keywords,
    meeting_text
):

    if not keywords:
        return []

    keyword_list = "\n".join(
        f"{i + 1}. {keyword}"
        for i, keyword in enumerate(keywords)
    )

    prompt = f"""
You are analyzing a business meeting.

Meeting transcript:
{meeting_text}

Important keywords:
{keyword_list}

For each keyword, provide a short description explaining
what that keyword means in the context of this meeting.

Return ONLY this format:

1. Keyword — Description
2. Keyword — Description
3. Keyword — Description

Do not invent information.
Keep each description to one or two sentences.
"""

    response = generate_with_phi(
        prompt,
        max_new_tokens=500
    )

    return response


# ============================================================
# 7. MEETING SUMMARY
# ============================================================

def generate_meeting_summary(
    meeting_text,
    keywords
):

    keyword_text = ", ".join(keywords)

    prompt = f"""
Analyze the following meeting transcript.

MEETING TRANSCRIPT:
{meeting_text}

KEYWORDS:
{keyword_text}

Create a clear meeting summary.

Use these sections:

1. Main Discussion
2. Important Conclusions
3. Decisions
4. Action Items
5. Issues or Concerns

Only include information supported by the transcript.

If a section is not mentioned in the meeting,
write "Not clearly mentioned."

Use concise bullet points.
"""

    return generate_with_phi(
        prompt,
        max_new_tokens=800
    )


# ============================================================
# 8. PARTICIPANT FEEDBACK
# ============================================================

def generate_participant_feedback(
    speaker,
    speaker_text,
    meeting_text,
    keywords
):

    keyword_text = ", ".join(keywords)

    prompt = f"""
Analyze the contribution of participant {speaker}
in a business meeting.

FULL MEETING CONTEXT:
{meeting_text}

MEETING KEYWORDS:
{keyword_text}

PARTICIPANT'S CONTRIBUTION:
{speaker_text}

Provide the feedback in English.

Use exactly these sections:

Contribution:
- Describe what the participant contributed.

Relevance:
- Explain how their comments relate to the meeting topics.

Strengths:
- Identify useful or constructive aspects of their contribution.

Suggestions:
- Give practical suggestions for improving future contributions.

Important:
- Be objective and constructive.
- Do not assign a numerical score.
- Do not make assumptions about personality.
- Do not invent statements that the participant did not make.
- Keep the feedback concise.
"""

    return generate_with_phi(
        prompt,
        max_new_tokens=600
    )


# ============================================================
# 9. BUILD SPEAKER TEXT
# ============================================================

def organize_speaker_text(diarized_segments):

    speaker_texts = defaultdict(list)

    for segment in diarized_segments:

        speaker = segment["speaker"]

        speaker_texts[speaker].append(
            segment["text"]
        )

    return {
        speaker: " ".join(texts)
        for speaker, texts
        in speaker_texts.items()
    }


# ============================================================
# 10. PRINT TRANSCRIPT
# ============================================================

def print_transcript(diarized_segments):

    print("\n" + "=" * 60)
    print("DIARIZED TRANSCRIPT")
    print("=" * 60)

    for segment in diarized_segments:

        start = segment["start"]
        end = segment["end"]
        speaker = segment["speaker"]
        text = segment["text"]

        print(
            f"[{start:.1f}s - {end:.1f}s] "
            f"{speaker}: {text}"
        )


# ============================================================
# 11. SAVE RESULTS
# ============================================================

def save_results(
    diarized_segments,
    keywords,
    keyword_descriptions,
    summary,
    feedback
):

    filename = "meeting_analysis_result.txt"

    with open(
        filename,
        "w",
        encoding="utf-8"
    ) as f:

        f.write("=" * 70 + "\n")
        f.write("AI MEETING ANALYSIS RESULT\n")
        f.write("=" * 70 + "\n\n")

        # ----------------------------------------------------
        # Transcript
        # ----------------------------------------------------

        f.write("1. DIARIZED TRANSCRIPT\n")
        f.write("-" * 70 + "\n\n")

        for segment in diarized_segments:

            f.write(
                f"[{segment['start']:.1f}s - "
                f"{segment['end']:.1f}s] "
                f"{segment['speaker']}: "
                f"{segment['text']}\n"
            )

        # ----------------------------------------------------
        # Keywords
        # ----------------------------------------------------

        f.write("\n\n")
        f.write("2. MEETING KEYWORDS\n")
        f.write("-" * 70 + "\n\n")

        for i, keyword in enumerate(
            keywords,
            start=1
        ):

            f.write(
                f"{i}. {keyword}\n"
            )

        # ----------------------------------------------------
        # Keyword descriptions
        # ----------------------------------------------------

        f.write("\n\n")
        f.write("3. KEYWORD DESCRIPTIONS\n")
        f.write("-" * 70 + "\n\n")

        f.write(
            keyword_descriptions
        )

        # ----------------------------------------------------
        # Summary
        # ----------------------------------------------------

        f.write("\n\n")
        f.write("4. MEETING SUMMARY\n")
        f.write("-" * 70 + "\n\n")

        f.write(summary)

        # ----------------------------------------------------
        # Participant feedback
        # ----------------------------------------------------

        f.write("\n\n")
        f.write("5. PARTICIPANT FEEDBACK\n")
        f.write("-" * 70 + "\n\n")

        for speaker, text in feedback.items():

            f.write(
                f"\n{speaker}\n"
            )

            f.write(
                "-" * 40 + "\n"
            )

            f.write(text)

            f.write("\n")

    print(
        f"\nResults saved to: {filename}"
    )


# ============================================================
# 12. FULL PIPELINE
# ============================================================

def run_full_analysis():

    print("\n")
    print("=" * 70)
    print("AI MEETING ANALYSIS SYSTEM")
    print("=" * 70)

    # --------------------------------------------------------
    # STEP 1
    # --------------------------------------------------------

    wav = record_meeting()

    # --------------------------------------------------------
    # STEP 2
    # --------------------------------------------------------

    audio, transcription = transcribe_audio(
        wav
    )

    # --------------------------------------------------------
    # STEP 3
    # --------------------------------------------------------

    diarized = diarize_audio(
        audio,
        transcription
    )

    print_transcript(
        diarized
    )

    # --------------------------------------------------------
    # Combine transcript
    # --------------------------------------------------------

    all_text = " ".join(
        segment["text"]
        for segment in diarized
    )

    if not all_text.strip():

        raise RuntimeError(
            "The transcription is empty."
        )

    # --------------------------------------------------------
    # STEP 4: KEYWORDS
    # --------------------------------------------------------

    keywords = extract_keywords(
        all_text
    )

    print("\n" + "=" * 60)
    print("MEETING KEYWORDS")
    print("=" * 60)

    for i, keyword in enumerate(
        keywords,
        start=1
    ):

        print(
            f"{i}. {keyword}"
        )

    # --------------------------------------------------------
    # STEP 5: KEYWORD DESCRIPTIONS
    # --------------------------------------------------------

    print("\n" + "=" * 60)
    print("KEYWORD DESCRIPTIONS")
    print("=" * 60)

    keyword_descriptions = (
        generate_keyword_descriptions(
            keywords,
            all_text
        )
    )

    print(
        keyword_descriptions
    )

    # --------------------------------------------------------
    # STEP 6: SUMMARY
    # --------------------------------------------------------

    print("\n" + "=" * 60)
    print("MEETING SUMMARY")
    print("=" * 60)

    summary = generate_meeting_summary(
        all_text,
        keywords
    )

    print(
        summary
    )

    # --------------------------------------------------------
    # STEP 7: PARTICIPANT FEEDBACK
    # --------------------------------------------------------

    print("\n" + "=" * 60)
    print("PARTICIPANT FEEDBACK")
    print("=" * 60)

    speaker_texts = organize_speaker_text(
        diarized
    )

    feedback = {}

    for speaker, speaker_text in speaker_texts.items():

        print(
            f"\nAnalyzing {speaker}..."
        )

        feedback[speaker] = (
            generate_participant_feedback(
                speaker,
                speaker_text,
                all_text,
                keywords
            )
        )

        print(
            f"\n--- {speaker} ---"
        )

        print(
            feedback[speaker]
        )

    # --------------------------------------------------------
    # STEP 8: SAVE EVERYTHING
    # --------------------------------------------------------

    save_results(
        diarized,
        keywords,
        keyword_descriptions,
        summary,
        feedback
    )

    print("\n")
    print("=" * 70)
    print("ANALYSIS COMPLETE")
    print("=" * 70)


