# 1. RECORD MEETING
# ============================================================

def record_meeting(
    filename=AUDIO_FILE,
    fs=SAMPLE_RATE,
    channels=CHANNELS
):
    print("\n" + "=" * 60)
    print("MEETING RECORDING")
    print("=" * 60)

    print("\nRecording started.")
    print("Speak normally.")
    print("Press ENTER to stop recording.\n")

    recording = []

    def callback(indata, frames, time, status):

        if status:
            print("Audio status:", status)

        recording.append(indata.copy())

    try:

        with sd.InputStream(
            samplerate=fs,
            channels=channels,
            dtype="float32",
            callback=callback
        ):

            input()

    except Exception as e:

        print("\nERROR while recording:")
        print(e)

        print("\nAvailable audio devices:")
        print(sd.query_devices())

        raise

    # --------------------------------------------------------
    # Prevent the old:
    # ValueError: need at least one array to concatenate
    # --------------------------------------------------------

    if len(recording) == 0:

        print("\nERROR: No audio data was recorded.")
        print("The microphone callback did not receive any data.")

        raise RuntimeError(
            "Recording is empty. Check microphone permissions "
            "and the selected input device."
        )

    audio = np.concatenate(recording, axis=0)

    if audio.size == 0:

        raise RuntimeError(
            "Recording contains zero audio samples."
        )

    # Remove extra channel dimension for soundfile
    if channels == 1:
        audio = audio[:, 0]

    sf.write(
        filename,
        audio,
        fs
    )

    duration = len(audio) / fs

    print(f"\nRecording saved: {filename}")
    print(f"Duration: {duration:.2f} seconds")

    return filename


